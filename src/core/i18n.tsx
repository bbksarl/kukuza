interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, values?: Record<string, string | number>) => string;
  translateCatalogLabel: (value: string | null | undefined) => string;
  translateText: (value: string | null | undefined) => string;
}

const defaultContext: LanguageContextValue = {
  language: 'fr',
  setLanguage: () => undefined,
  t: (key, values) => interpolate(messages.fr[key] ?? key, values),
  translateCatalogLabel: (value) => value ?? '',
  translateText: (value) => value ?? '',
};

const LanguageContext = createContext<LanguageContextValue>(defaultContext);

function interpolate(value: string, values?: Record<string, string | number>) {
  if (!values) return value;
  return Object.entries(values).reduce((result, [key, replacement]) => result.replace(`{${key}}`, String(replacement)), value);
}

function readStoredLanguage(): Language {
  if (typeof window === 'undefined') return 'fr';
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en' ? 'en' : 'fr';
}

export function LanguageProvider({ children }: PropsWithChildren) {
  const [language, setLanguage] = useState<Language>(readStoredLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    window.dispatchEvent(new CustomEvent('kukuza:language-change', { detail: { language } }));
  }, [language]);

  const t = useCallback((key: string, values?: Record<string, string | number>) => {
    const text = messages[language][key] ?? messages.fr[key] ?? key;
    return interpolate(text, values);
  }, [language]);

  const translateCatalogLabel = useCallback((value: string | null | undefined) => {
    if (!value) return '';
    const directMatch = catalogLabels[value];
    if (directMatch) return directMatch[language];

    const normalizedValue = value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase();
    const matchingEntry = Object.entries(catalogLabels).find(([label]) => (
      label.normalize('NFD').replace(/[\u0300-\u036f]/g, '').trim().toLowerCase() === normalizedValue
    ));

    return matchingEntry?.[1][language] ?? value;
  }, [language]);

  const translateText = useCallback((value: string | null | undefined) => {
    if (!value || language === 'fr') return value ?? '';
    return freeTextTranslations[value] ?? value;
  }, [language]);

  const contextValue = useMemo(() => ({ language, setLanguage, t, translateCatalogLabel, translateText }), [language, t, translateCatalogLabel, translateText]);

  return <LanguageContext.Provider value={contextValue}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

